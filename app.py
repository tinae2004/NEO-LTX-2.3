def inspect_dataset(path_text):
    path = Path(path_text).expanduser()
    if not path.exists():
        return "Path does not exist.", ""
    manifests = [path] if path.is_file() else sorted(path.rglob("manifest.json"))
    if not manifests:
        return "No manifest.json found.", ""
    reports = []
    for manifest in manifests[:100]:
        try:
            reports.append(validate_manifest(manifest))
        except Exception as error:
            reports.append({"manifest": str(manifest), "valid": False, "errors": [str(error)]})
    return f"Inspected {len(reports)} manifest(s).", json.dumps(reports, indent=2)


def run_ltx(endpoint, workflow_file, prompt, prompt_node, start_image, image_node, timeout):
    if workflow_file is None:
        raise gr.Error("Upload a ComfyUI API-format LTX-2.3 workflow JSON.")
    try:
        output = generate_video(
            endpoint,
            Path(workflow_file).read_text(encoding="utf-8"),
            prompt,
            str(prompt_node).strip(),
            str(start_image) if start_image else None,
            str(image_node).strip() if image_node else None,
            timeout_seconds=int(timeout),
        )
    except Exception as error:
        raise gr.Error(f"LTX generation failed: {error}") from error
    return output, f"LTX-2.3 generation complete: {output}"


def run_hunyuan(
    endpoint, workflow_file, prompt, prompt_node, start_image, image_node,
    sampler_node, steps, timeout
):
    if workflow_file is None:
        raise gr.Error("Upload a ComfyUI API-format HunyuanVideo 1.5 480p I2V workflow.")
    if start_image is None:
        raise gr.Error("Hunyuan 480p step-distilled mode requires a character start image.")
    if not str(sampler_node).strip():
        raise gr.Error("Enter the sampler node ID from your exported workflow.")
    try:
        output = generate_video(
            endpoint,
            Path(workflow_file).read_text(encoding="utf-8"),
            prompt,
            str(prompt_node).strip(),
            str(start_image),
            str(image_node).strip(),
            timeout_seconds=int(timeout),
            sampler_node_id=str(sampler_node).strip(),
            sampler_steps=int(steps),
        )
    except Exception as error:
        raise gr.Error(f"Hunyuan generation failed: {error}") from error
    return output, f"HunyuanVideo 1.5 480p generation complete ({steps} steps): {output}"


